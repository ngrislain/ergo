#!/usr/bin/env python3
"""Regenerate the embedded LDraw color catalog from the official LDConfig file."""
import hashlib
import argparse
import json
import pathlib
import re
import urllib.request

URL = "https://library.ldraw.org/library/official/LDConfig.ldr"
parser = argparse.ArgumentParser()
parser.add_argument("--source", type=pathlib.Path, help="Use an already downloaded official LDConfig.ldr")
args = parser.parse_args()
if args.source:
    data = args.source.read_bytes()
else:
    request = urllib.request.Request(URL, headers={"User-Agent": "Ergo catalog updater (+https://github.com/NGrislain/ergo)"})
    with urllib.request.urlopen(request, timeout=30) as response:
        data = response.read(2 * 1024 * 1024 + 1)
assert len(data) <= 2 * 1024 * 1024, "LDConfig exceeds download limit"
text = data.decode("utf-8-sig")
colors = {}
for line in text.splitlines():
    match = re.match(r"0 !COLOUR (\S+)\s+CODE\s+(\d+)\s+VALUE #([0-9a-fA-F]{6})\b", line)
    if match:
        name, code, rgb = match.groups()
        alpha = re.search(r"\bALPHA (\d+)", line)
        code = int(code)
        assert code not in colors, f"Duplicate color {code}"
        colors[code] = (name.replace("_", " "), int(rgb, 16), int(alpha[1]) if alpha else 255)
assert len(colors) >= 200, "Incomplete LDConfig color catalog"
update = next(line for line in text.splitlines() if "!LDRAW_ORG Configuration UPDATE" in line)
lines = [f"// Generated by scripts/update-ldraw-colors.py from {URL}",
         f"// {update}; SHA256 {hashlib.sha256(data).hexdigest()}",
         "pub const COLORS: &[(u32, &str, u32, u8)] = &["]
for code, (name, rgb, alpha) in sorted(colors.items()):
    lines.append(f"    ({code}, {json.dumps(name, ensure_ascii=False)}, 0x{rgb:06x}, {alpha}),")
lines.append("];\n")
path = pathlib.Path(__file__).resolve().parents[1] / "crates/world/src/ldraw_colors.rs"
path.write_text("\n".join(lines))
print(f"Generated {len(colors)} LDraw colors: {path}")
